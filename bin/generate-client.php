<?php

/**
 * Regenerates src/Client.php and the "Available resources" block in README.md
 * from the generated src/Api/*Api.php classes. Run after openapi-generator.
 */

$root = dirname(__DIR__);

$apis = [];
foreach (glob($root . '/src/Api/*Api.php') as $file) {
    $class = basename($file, '.php');
    preg_match_all('/public function (\w+)\(/', file_get_contents($file), $matches);
    $operations = array_values(array_filter(
        $matches[1],
        fn (string $method) => !preg_match('/(Async|AsyncWithHttpInfo|WithHttpInfo|Request)$|^(__construct|getConfig|getHostIndex|setHostIndex)$/', $method),
    ));
    sort($operations);
    $apis[lcfirst(substr($class, 0, -3))] = ['class' => $class, 'operations' => $operations];
}
ksort($apis);

$uses = implode("\n", array_map(fn (array $api) => "use SimplyCom\\Api\\{$api['class']};", $apis));
$methods = implode("\n", array_map(
    fn (string $accessor, array $api) => <<<PHP

        public function {$accessor}(): {$api['class']}
        {
            return new {$api['class']}(\$this->http, \$this->config);
        }
    PHP,
    array_keys($apis),
    $apis,
));

file_put_contents($root . '/src/Client.php', <<<PHP
<?php

namespace SimplyCom;

use GuzzleHttp\Client as GuzzleClient;
use GuzzleHttp\ClientInterface;
{$uses}

/**
 * Single entry-point for the Simply.com API.
 *
 *     \$simply = new SimplyCom\Client('your-api-key');
 *     \$simply->products()->getProductList();
 *
 * This file is generated by bin/generate-client.php, do not edit it manually.
 */
final class Client
{
    private readonly Configuration \$config;

    private readonly ClientInterface \$http;

    public function __construct(
        string \$apiKey,
        ?ClientInterface \$http = null,
    ) {
        \$this->config = (new Configuration())->setAccessToken(\$apiKey);
        \$this->http = \$http ?? new GuzzleClient();
    }
{$methods}
}

PHP);

$width = max(array_map('strlen', array_keys($apis))) + 12;
$resources = implode("\n", array_map(
    fn (string $accessor, array $api) => str_pad("\$simply->{$accessor}()", $width) . '// ' . implode(', ', $api['operations']),
    array_keys($apis),
    $apis,
));

$readme = file_get_contents($root . '/README.md');
$readme = preg_replace(
    '/(<!-- resources -->\n).*?(<!-- \/resources -->)/s',
    "\$1```php\n" . str_replace('$', '\\$', $resources) . "\n```\n\$2",
    $readme,
    1,
    $count,
);
if ($count !== 1) {
    fwrite(STDERR, "README.md is missing the <!-- resources --> markers\n");
    exit(1);
}
file_put_contents($root . '/README.md', $readme);
